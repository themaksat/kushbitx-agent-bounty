import { createHash, generateKeyPairSync, sign } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";

const API = "https://api.moltrust.ch";
const OUT = "evidence/moltrust-taskmarket.json";

function leadingZeroBits(buf) {
  let n = 0;
  for (const byte of buf) {
    if (byte === 0) { n += 8; continue; }
    for (let bit = 7; bit >= 0; bit--) {
      if ((byte & (1 << bit)) === 0) n++;
      else return n;
    }
  }
  return n;
}

async function jsonFetch(url, init = {}) {
  const response = await fetch(url, {
    ...init,
    headers: { accept: "application/json", ...(init.body ? { "content-type": "application/json" } : {}), ...(init.headers || {}) },
  });
  const raw = await response.text();
  let body;
  try { body = JSON.parse(raw); } catch { body = { raw }; }
  if (!response.ok) throw new Error(`${url} -> HTTP ${response.status}: ${raw.slice(0, 800)}`);
  return { status: response.status, body };
}

const challengeResponse = await jsonFetch(`${API}/identity/register-challenge`);
const challenge = challengeResponse.body.challenge;
const seed = challengeResponse.body.pow?.seed;
const difficulty = Number(challengeResponse.body.pow?.difficulty_bits ?? 18);
if (!challenge || !seed || !Number.isFinite(difficulty)) throw new Error("Malformed MolTrust challenge");

let powNonce = null;
for (let i = 0; i < 20_000_000; i++) {
  const candidate = String(i);
  const digest = createHash("sha256").update(seed + candidate).digest();
  if (leadingZeroBits(digest) >= difficulty) { powNonce = candidate; break; }
}
if (powNonce == null) throw new Error("PoW solution not found within bound");

const { publicKey, privateKey } = generateKeyPairSync("ed25519");
const jwk = publicKey.export({ format: "jwk" });
const publicKeyHex = Buffer.from(jwk.x, "base64url").toString("hex");
const signature = sign(null, Buffer.from(challenge, "utf8"), privateKey).toString("base64url");

const registration = await jsonFetch(`${API}/identity/register-pop`, {
  method: "POST",
  body: JSON.stringify({
    public_key: publicKeyHex,
    challenge,
    signature,
    pow_nonce: powNonce,
    display_name: "RevenueSwarmAgent",
    platform: "taskmarket",
  }),
});

const rb = registration.body;
const did =
  rb.did ||
  rb.agent_did ||
  rb.id ||
  rb.credential?.credentialSubject?.id ||
  rb.credential?.credentialSubject?.did ||
  rb.vc?.credentialSubject?.id;
if (typeof did !== "string" || !did.startsWith("did:moltrust:")) {
  throw new Error(`Could not resolve registered DID from response keys: ${Object.keys(rb).join(",")}`);
}

const score = await jsonFetch(`${API}/skill/trust-score/${encodeURIComponent(did)}`);

const evidence = {
  schema: "revenue-swarm.moltrust-taskmarket-evidence/v1",
  task_id: "0xea9b5bd5310567979355dcc4a14995a21769cc413c4f29a3b83b03429f461168",
  task_reference: "TSK-9YFR1YF7",
  did,
  platform: "taskmarket",
  registration_http_status: registration.status,
  trust_score_http_status: score.status,
  trust_score_response: score.body,
  generated_at: new Date().toISOString(),
  note: "Generated by GitHub Actions using MolTrust's free keyless Ed25519 proof-of-possession flow. Private key and signature are intentionally not persisted.",
};

await mkdir("evidence", { recursive: true });
await writeFile(OUT, JSON.stringify(evidence, null, 2) + "\n", "utf8");
console.log(JSON.stringify({ did, score: score.body, output: OUT }, null, 2));
